#!/usr/bin/env python3

num1 = int(input("Give me a first number: "))
num2 = int(input("Give me a second number: "))
result = num1 + num2
print(f"{num1} + {num2} = {result}")
result = num1 - num2
print(f"{num1} - {num2} = {result}")
result = num1 / num2
print(f"{num1} / {num2} = {result}")
result = num1 * num2
print(f"{num1} * {num2} = {result}")